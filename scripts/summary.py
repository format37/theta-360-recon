#!/usr/bin/env python3
"""Every number of a run on one page, collected from the JSON files of the steps. From galaxy-s26-ultra-stereo.

    python3 -I scripts/summary.py data/pool/rig.yaml

It only reads; a step that has not run yet is left out. Writes out/<variant>/summary.md.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from project import load

p = load(sys.argv[1])


def js(path):
    path = p.run / path
    return json.load(open(path)) if path.exists() else None


L = [f'# {p.name}: numbers of the run', '', f'Generated by `scripts/summary.py` from `out/{p.yaml.stem}/product/*.json`. Unit: one lens height '
     f'(the median height of the lens above the {"ground under each shot" if p.outdoor else "floor"})' + (f' = {p.camera_height_cm} cm.' if p.camera_height_cm else '; no tape number yet, so no metres.'), '']
row = lambda *c: L.append('| ' + ' | '.join(str(x) for x in c) + ' |')
table = lambda title: L.extend([f'## {title}', '', '| | |', '|---|---|'])

i = js('product/inspect.json'); fc = js('product/faces.json')
if i:
    table('Input')
    row('Photos', f"{i['shots']} stitched equirectangular panoramas {i['size'][0][0]}x{i['size'][0][1]}, {', '.join(i['camera'])} ({', '.join(i['firmware'])}), one every {i['interval_s'][1]:.0f} s, {i['duration_s'] / 60:.1f} min")
    row('Exposure', f"program {i['exposure_program']} (2 = auto), shutter {i['shutter_s'][0]:.4f}-{i['shutter_s'][1]:.4f} s, ISO {i['iso']}: {i['exposure_range_stops']} stops of drift")
    row("Camera's own tilt", f"pitch {i['camera_pitch_deg'][0]} .. {i['camera_pitch_deg'][1]} deg, roll {i['camera_roll_deg'][0]} .. {i['camera_roll_deg'][1]} deg; GPS in {i['gps_in_exif']} files")
    o = i['overlap']
    row('Overlap of neighbours', '; '.join(f"i+{k.split('+')[-1]}: {v['matches_median']:.0f} matches" for k, v in o.items()) + ' (SIFT on the masked panorama, no geometry)')
    L.append('')
if fc:
    table('Faces and masks')
    row('Faces', f"{len(fc['views'])} per panorama, {fc['size']} px, focal {fc['focal']:.0f} px; " + ', '.join(f'[{y:.0f}, {pt:.0f}]' for y, pt in fc['views']))
    if 'semantic' in fc:
        row('Masked', f"{fc['semantic']} by {fc['seg_model']}; the faces cover {fc['faces_cover_pct_of_panorama']}% of the panorama's pixels (the rest is round the nadir)")
        row('Sky per face', ' '.join(f'v{v:02d} {100 * x:.0f}%' for v, x in enumerate(fc['sky_share'])))
        row('People per face', ' '.join(f'v{v:02d} {100 * x:.1f}%' for v, x in enumerate(fc['people_share'])))
    row('Usable per face', ' '.join(f'v{v:02d} {100 * x:.0f}%' for v, x in enumerate(fc['usable_share'])))
    L.append('')

pr, m, f, al = js('product/pairs.json'), js('product/matches.json'), js('product/sfm.json'), js('product/align.json')
if pr or m or f:
    table('Sparse model')
    if pr: row('Pairs', f"{pr['panorama_pairs_sequential']} sequential (window {pr['window']}) + {pr['panorama_pairs_retrieval']} retrieval panorama pairs -> {pr['face_pairs']:,} face pairs "
                        f"(of {pr['face_pairs_if_all']:,}); putative matches with the next shot: median {pr['putative_matches_next_shot']['median']}, min {pr['putative_matches_next_shot']['min']}")
    if m: row('Verified', f"{m['face_pairs_verified']:,} face pairs in {m['panorama_pairs_verified']:,} panorama pairs; loop closures {m['loop_closures']}, touching "
                          f"{m['panoramas_in_a_loop_closure']} panoramas; weak panoramas: {len(m['weak_panoramas'])}")
    if f:
        row('Registered', f"{f['panoramas_registered']}/{f['panoramas_total']} panoramas = {f['images_registered']}/{f['images_total']} faces; {f['points']:,} points, track length {f['track_length_mean']}")
        row('Reprojection error', f"{f['reproj_px_mean']} px mean at focal {f['focal_px']:.0f} px = {f['reproj_deg_mean']} deg mean, {f['reproj_deg_median']} median, {f['reproj_deg_p95']} at the 95th percentile")
        s = f['seam']; row('Stitching seam', '; '.join(f"{k}: {v['deg_mean']} deg, {100 * v['triangulated_share']:.0f}% triangulated" for k, v in s.items()))
    sp = js('../spherical/product/spherical.json')
    if sp and 'vs_rig' in sp:
        v = sp['vs_rig']; row('OpenMVG, spherical camera', f"{sp['panoramas_registered']}/{sp['panoramas_total']} panoramas, {sp['reproj_deg_mean']} deg; against the rig: centres {v['centre_rms_pct_of_path']}% "
                                                          f"of the path apart (rms), orientations {v['rotation_deg_median']} deg (median)")
    L.append('')
if al:
    table('Scene frame')
    if al.get('scene') == 'outdoor':
        row('Up', f"{al['up_source']}; the panoramas' own up directions within {al['panorama_up_deg_from_mean']['median']:.2f} deg of their mean (median), {al['panorama_up_deg_from_mean']['max']:.2f} at most")
        row('Ground plane', f"the largest one near the walk is {al['ground_plane_deg_from_up']:.2f} deg from that up")
        row('Lens height above the ground', f"measured at {al['shots_with_ground']} shots (the others from their neighbours); 10-90%: {al['lens_height_p10_p90'][0]:.2f} .. "
                                            f"{al['lens_height_p10_p90'][1]:.2f} of the median, spread {al['lens_height_spread_pct']:.1f}% (a pole carried by hand)")
        row('Ground', f"its height under the shots ranges {al['ground_height_range'][0]:+.2f} .. {al['ground_height_range'][1]:+.2f} lens heights")
        row('Walk', f"{al['path_length']:.1f} lens heights over an area of {al['walked_area'][0]:.1f} x {al['walked_area'][1]:.1f}; median step {al['step_median_lens_heights']:.2f}; start to end {al['path_end_to_end']:.1f}")
        if al.get('taken_out_after_aligning'): row('Taken out', f"{', '.join(al['taken_out_after_aligning'])}: {al['taken_out_note']}")
    else:
        row('Floor', f"{al['floor_points']} sparse points; spread of the lens heights above it {al['lens_height_spread_pct']:.2f}%; path {al['path_length_in_camera_heights']:.2f} lens heights")
    L.append('')

pri, me, cov = js('product/prior.json'), js('product/mesh.json'), js('product/mesh_coverage.json')
if me:
    table('Dense cloud and mesh')
    a = me['all_pixels']
    row('Faces', f"{me['faces']} of {me['panoramas']} panoramas at {me['size']} px")
    walls = [pl for pl in me['planes'] if pl['kind'] == 'wall']
    row('Planes', '; '.join(f"{pl['kind']} at z {pl['z']:.2f}" for pl in me['planes'] if pl['kind'] != 'wall') + (f'; ' if len(walls) < len(me['planes']) else '')
        + f"{len(walls)} {'facades' if p.outdoor else 'walls'}")
    row('Pixels with a depth', f"PatchMatch {a['patchmatch']}% ({a['patchmatch_confirmed']}% confirmed from another panorama) -> with prior and planes {a['filled']}% ({a['filled_confirmed']}% confirmed)")
    row('Confirmed share by kind', f"PatchMatch {a['confirmed_share_of_patchmatch_pixels']}%, plane {a['confirmed_share_of_plane_pixels']}%, prior only {a['confirmed_share_of_prior_pixels']}%")
    if pri: row('Prior against PatchMatch', f"{pri['model'].split('/')[-1]}: {pri['median_rel_error_one_scale_pct']:.1f}% with one scale per face, {pri['median_rel_error_with_field_heldout_pct']:.1f}% "
                                            f"with the smooth field (held-out blocks), {pri['faces_aligned']}/{pri['faces']} faces")
    for k, nm in (('mesh_patchmatch_only', 'Mesh, PatchMatch only'), ('mesh', 'Mesh, with prior and planes')):
        g = me[k]; row(nm, f"{g['triangles']:,} triangles, area {g['area']:.0f} lens heights^2, of it {g['wall_area']:.0f} on {'facade' if p.outdoor else 'wall'} planes")
    if cov: row('Real views covered by the mesh', '; '.join(f"{k}: {v['mean']}% (worst {v['worst']}%)" for k, v in cov.items()))
    L.append('')
vx = js('product/voxels.json')
if vx:
    table('Voxel model')
    row('Voxels', f"{vx['voxels']:,} of {vx['voxel_lens_heights']} lens heights, {vx['extent_lens_heights'][0]:.1f} x {vx['extent_lens_heights'][1]:.1f} x {vx['extent_lens_heights'][2]:.1f} lens heights; "
                  f"cube mesh {vx['cube_mesh_triangles']:,} triangles")
    row('From', f"{vx['faces']} faces of {vx['panoramas']} panoramas, source `{vx['source']}`: PatchMatch {vx['share_by_source_pct']['patchmatch']}%, planes {vx['share_by_source_pct']['plane']}%, "
                f"prior {vx['share_by_source_pct']['prior']}%; seen from {vx['views_median']} panoramas (median)")
    row('Dropped', f"of {vx['on_the_fused_surface']:,} voxels on the fused surface: {vx['dropped_under_min_views']:,} seen from too few panoramas, {vx['dropped_small_groups']:,} in small groups, "
                   f"{vx['dropped_beyond_reach']:,} beyond the reach")
    L.append('')
sp = sorted(p.run.glob('splat*/metrics.json'))
if sp:
    L += ['## Splat', '', 'Held-out panoramas, never trained on: `inside` between trained shots, `beyond` past the end of the walk, `pass` a whole later pass '
          '(`--holdout-from`). PSNR and SSIM on the scene pixels; in brackets PSNR with the sky; LPIPS (AlexNet) on the whole face with the sky. '
          'Nearest: lens heights from a held-out panorama to the nearest trained one (median).', '',
          '| run | Gaussians | test | panoramas | nearest | PSNR | SSIM | LPIPS | train PSNR | minutes |', '|---|---|---|---|---|---|---|---|---|---|']
    for fpath in sp:
        g = json.load(open(fpath))
        for k in ('inside', 'beyond', 'pass'):
            if k not in g: continue
            t = g[k]
            row(f'`{fpath.parent.name}`', f"{g['gaussians']:,}", k, len(t['panoramas']) if 'panoramas' in t else '', t.get('nearest_trained_median', ''),
                f"{t['psnr']} dB" + (f" ({t['psnr_with_sky']} dB)" if 'psnr_with_sky' in t else ''), t['ssim'], t.get('lpips', ''), g['train']['psnr'], round(g['train_time_s'] / 60, 1))
    L.append('')
ms = js('product/measure.json')
if ms and ms['lengths']:
    L += ['## Lengths to check with a tape', '', '| length | lens heights | cm | tape, cm | error |', '|---|---|---|---|---|']
    for o in ms['lengths']:
        row(o['label'], f"{o['lens_heights']:.2f}", f"{o['cm']:.0f}" if o.get('cm') else '', o.get('tape_cm', ''), f"{o['error_pct']:+.2f}%" if 'error_pct' in o else '')
    L.append('')
(p.run / 'summary.md').write_text('\n'.join(L))
print('\n'.join(L)); print('wrote', p.run / 'summary.md')
